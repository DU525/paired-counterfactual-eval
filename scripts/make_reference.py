"""Generate reference/toy_verdicts.json from an actual run.

The file is committed so that a metric regression shows up as a diff, not only
as a failing test. Regenerate deliberately:

    python scripts/make_reference.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pcf_eval.aggregate import aggregate  # noqa: E402
from pcf_eval.protocol import evaluate_origin, load_backend, load_spec  # noqa: E402
from pcf_eval.toy import (  # noqa: E402
    ToyBaseline,
    ToyCandidateModel,
    ToyConfig,
    ToyRingEnv,
)

CONFIGS = ["toy.yaml", "toy_inconclusive.yaml", "toy_ranking_limited.yaml"]
RESAMPLES = 4000


def build(config_path: Path):
    spec = load_spec(config_path)
    toy = dict(load_backend(config_path).get("toy", {}))
    cfg = ToyConfig(
        n_states=int(toy.get("n_states", 12)),
        n_actions=int(toy.get("n_actions", 4)),
        horizon=int(toy.get("horizon", 4)),
        n_goals=int(toy.get("n_goals", 1)),
        steps=tuple(toy.get("steps", (1, 2, -1, 3))),
        goal_offset=int(toy.get("goal_offset", 5)),
        model_noise=float(toy.get("model_noise", 0.0)),
        model_score_jitter=float(toy.get("model_score_jitter", 0.0)),
        seed=int(toy.get("seed", 0)),
    )
    baseline_action = int(toy.get("baseline_action", 0))
    return (
        spec,
        ToyRingEnv(cfg),
        ToyCandidateModel(cfg, baseline_action),
        ToyBaseline(baseline_action),
    )


def main() -> int:
    out = {"_comment": "Generated by scripts/make_reference.py. Do not hand-edit.", "configs": {}}
    for name in CONFIGS:
        spec, env, model, baseline = build(ROOT / "configs" / name)
        results = [evaluate_origin(env, model, baseline, spec, int(s)) for s in spec.seeds]
        summary = aggregate(results, resamples=RESAMPLES)
        out["configs"][name] = {
            "spec_name": spec.name,
            "verdict": summary.verdict,
            "mechanism": summary.mechanism,
            "n_origins": summary.n_origins,
            "n_candidates": summary.n_candidates,
            "resamples": RESAMPLES,
            "opportunity": {
                "mean": round(summary.opportunity.mean, 6),
                "low": round(summary.opportunity.low, 6),
                "high": round(summary.opportunity.high, 6),
            },
            "ranking_regret": {
                "mean": round(summary.ranking_regret.mean, 6),
                "low": round(summary.ranking_regret.low, 6),
                "high": round(summary.ranking_regret.high, 6),
            },
            "value_gain": {
                "mean": round(summary.value_gain.mean, 6),
                "low": round(summary.value_gain.low, 6),
                "high": round(summary.value_gain.high, 6),
            },
            "top1_rate": round(summary.top1_rate.mean, 6),
            "random_top1_rate": round(summary.random_top1_rate, 6),
            "max_identity_residual": max(r.coverage.identity_residual for r in results),
        }
    target = ROOT / "reference" / "toy_verdicts.json"
    target.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
    for name, rec in out["configs"].items():
        print(f"  {name:<28} {rec['verdict']:<22} {rec['mechanism']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
